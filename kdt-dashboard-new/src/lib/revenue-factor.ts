// 매출 보정의 단일 정의 — 이탈시점 가중 θ
//
// 한때 같은 계수가 두 곳(revenue-engine.ts, data-utils.ts)에 복붙돼 있었고,
// 계단식 분기라 무엇을 가정한 산식인지 읽히지 않았다. 여기만 고친다.
//
// ── 산식의 근거 ────────────────────────────────────────────────
// 데이터셋(엑셀)의 매출 컬럼은 다음과 같이 만들어진다:
//   매출 최대   = 훈련비 × 수강신청 인원
//   매출 최소   = 훈련비 × 수료인원
//   실 매출 대비 = 매출 최대 × 0.8          ← BASE_REVENUE_RATIO
//   연도별      = 실 매출 대비 × (그 해 달력일수 / 총 달력일수)
// (2026-09-15 기준 7,230행 전수 검증, 불일치 0건)
//
// 실제로는 중도이탈자도 이탈 시점까지의 훈련비가 지급된다
// (운영규정 제47조 1항: 단위기간 출석률 80% 이상 A×B, 미만 A×B×C).
// 개인별 출석은 데이터셋에 없으므로 정확 계산은 원리적으로 불가능하고,
// "이탈자가 평균적으로 소화한 훈련기간 비율" θ 하나로 모수화한다.
//
//   실매출 = 훈련비 × [ 수료인원 + (수강신청 인원 − 수료인원) × θ ]
//          = 매출 최대 × [ r + (1 − r) × θ ]        (r = 수료율)
//
// 이 값이 항상 매출 최소 이상, 매출 최대 이하가 된다 — 논리적으로 닫혀 있다.
//
// ── 예전 계수와의 관계 ─────────────────────────────────────────
// 기존 계단식 계수(>=100 → 1.25, >=75 → 1.0+.., >=50 → 0.75+.., else 0.75)는
// 수료율 50~100% 구간에서 정확히 θ=0.20 과 대수적으로 동일하다:
//   0.8 × (0.25 + r) = 0.2 + 0.8r ⟺ r + (1−r)×0.20
// 달라지는 곳은 수료율 50% 미만뿐이다. 거기서 옛 계수는 0.75 로 평평해져
// 역산 θ 가 0.20 → 0.33(40%) → 0.43(30%) → 0.60(0%) 으로 **역진**했다.
// 많이 이탈한 코호트일수록 이탈자 1인당 매출을 더 쳐주는 셈이라 방향이 거꾸로였다.
// (전수 영향: 종료분 17,507.1억 → 17,424.7억, −0.5%. 금액은 작고 논리만 바로잡힌다.)

/**
 * 이탈자가 평균적으로 소화한 훈련기간 비율 θ.
 *
 * ── 0.39 의 근거 (2026-09-15 실측) ─────────────────────────────
 * 직전 값 0.20 은 옛 계단식 계수가 암묵적으로 쓰던 숫자일 뿐 실측이 아니었다.
 * 독립적인 세 방법이 전부 0.39 로 수렴한다.
 *
 *   ① 출석부 원본  `Downloads/출석률 계산/*.xlsx` 157파일 6,352명
 *      (그중 미수료 1,076명, 2021~2026)                        → 0.392
 *      학생별로 운영규정 47조1항을 그대로 적용:
 *        E = (출석+결석+휴가+공가)/총훈련일수   (재적 기간 비율)
 *        A = 출석일수/총훈련일수                (출석 비율)
 *        θ = E  if (A/E) >= 0.8  else  A       (단위기간 80% 넘으면 전액)
 *   ② 실제 청구액  월별 비용신청 시트, 청구가 끝까지 찍힌 종강 17개 기수
 *      θ = (R·N − G)/(N − G),  R = Σ신청/Σ예상 = 0.880       → 0.387
 *   ③ 수료율 c 와 매출배분율 R 의 회귀 (기수 141개, 인원가중)   → 0.391
 *      R = 0.391 + 0.609·c,  R² = 0.911
 *      이론식 R = θ + (1−θ)·c 와 대조하면 절편이 곧 θ 이고,
 *      절편+기울기 = 1.000 으로 정확히 맞는다.
 *
 * 기수 단위 군집 부트스트랩 95% 신뢰구간 **0.373 ~ 0.410** (기수 136개).
 *
 * ── 왜 상수 하나로 충분한가 ────────────────────────────────────
 * θ 는 **수료율과 무관하다**: 기수 141개 회귀에서 θ = 0.388 + 0.005·c (R² ≈ 0).
 * 수료율 십분위별로도 0.355~0.409 로 평평하다. 수료율이 매출배분율을 좌우하는 건
 * 맞지만(R² 0.911) 그건 위 식의 `c` 항이 이미 전부 설명한다 — θ 는 그 직선의
 * 절편일 뿐이다. 그래서 수료율이 우리와 다른 기관에 같은 θ 를 적용해도 된다.
 * (세분화 이득도 작다: 과정 계열별 0.336~0.475, 훈련기간별 0.371~0.410)
 *
 * ── 알려진 불일치 ──────────────────────────────────────────────
 * `backend/retention-curve.ts` 의 잔존율 곡선은 θ = α/(α+1) 과 동치라
 * 기본값 α=0.5 가 θ=0.333 을 뜻한다. 실측 0.392 에 대응하는 α 는 0.645 다.
 * 그쪽은 월별 매출 배분에 쓰이므로 별도 검토 대상 — 여기서는 건드리지 않는다.
 */
export const DROPOUT_WEIGHT = 0.39;

/** 데이터셋 `실 매출 대비` 가 `매출 최대` 에 곱해 둔 상수. */
export const BASE_REVENUE_RATIO = 0.8;

/** 매출 최대 대비 실매출 비율 = r + (1 − r)·θ */
export function revenueRatioFromCompletionRate(completionRatePercent: number): number {
  const r = Math.min(Math.max(completionRatePercent / 100, 0), 1);
  return r + (1 - r) * DROPOUT_WEIGHT;
}

/**
 * `실 매출 대비`(= 매출 최대 × 0.8)에 곱할 보정 계수.
 *
 * 수료율이 0 이하/NaN 이면 **보정하지 않는다(1.0)**. 수료율 0 은 "0% 수료"가
 * 아니라 "아직 미확정"이기 때문이다. 0 을 그대로 산식에 넣으면 이탈자 전원이
 * 실제로 이탈한 것으로 계산돼 매출이 통째로 깎인다.
 * 미확정 회차의 수료율 추정은 revenue-engine 의 estimateCompletionRate 가 맡는다.
 */
export function calculateRevenueAdjustmentFactor(completionRatePercent: number): number {
  if (!Number.isFinite(completionRatePercent) || completionRatePercent <= 0) return 1.0;
  return revenueRatioFromCompletionRate(completionRatePercent) / BASE_REVENUE_RATIO;
}

