export type CompletionRateSource =
  | '실측'
  /** 반영 지연 중이지만 이미 올라온 수료인원이 추정치보다 높아 그쪽을 쓴 경우 */
  | '부분실측'
  | '동일과정'
  | '기관×NCS'
  | '기관'
  | 'NCS'
  | '전체'
  | '미확정';
